export const PARTICLE_PRESET_MAP: Readonly<Record<ParticlePresetId, ParticlePreset>> = Object.freeze(
  Object.fromEntries(PARTICLE_PRESETS.map(preset => [preset.id, preset])) as Record<ParticlePresetId, ParticlePreset>
)

export function createDefaultParticleParams(presetId: ParticlePresetId = 'magnetic-vortex'): ParticleSimulationParams {
  const preset = PARTICLE_PRESET_MAP[presetId] ?? PARTICLE_PRESETS[0]
  return {
    ...preset.params,
    particleColors: [...preset.params.particleColors],
  }
}
