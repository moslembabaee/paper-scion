import type { ShaderPaint } from '../types.ts'
import { proceduralNoiseFragmentShader, proceduralNoiseUniforms } from './noiseFragment.ts'

export function exportProceduralNoiseReact(paint: Extract<ShaderPaint, { kind: 'procedural-noise' }>): string {
  const uniforms = proceduralNoiseUniforms(paint)
  const escapedGlsl = JSON.stringify(proceduralNoiseFragmentShader)

  return `// Generated by Paper (https://paper.design)
// Procedural Noise and Grain Displacement Shader Material Engine
import React from 'react'
import { ShaderMount } from '@paper-design/shaders-react'

export interface ProceduralNoiseProps {
  className?: string
  style?: React.CSSProperties
  speed?: number
  frame?: number
}

const FRAGMENT_SHADER = ${escapedGlsl}

const UNIFORMS = ${JSON.stringify(uniforms, null, 2)}

export default function ProceduralNoiseMaterial({
  className,
  style,
  speed = ${paint.speed},
  frame = ${paint.frame},
}: ProceduralNoiseProps) {
  return (
    <div
      className={className}
      style={{
        width: '100%',
        height: '100%',
        position: 'relative',
        overflow: 'hidden',
        mixBlendMode: ${JSON.stringify(paint.composite?.blendMode ?? 'normal')},
        opacity: ${paint.composite?.opacity ?? 1},
        ...style,
      }}
    >
      <ShaderMount
        fragmentShader={FRAGMENT_SHADER}
        uniforms={UNIFORMS}
        speed={speed}
        frame={frame}
        style={{ position: 'absolute', inset: 0, width: '100%', height: '100%' }}
      />
    </div>
  )
}
`
}
