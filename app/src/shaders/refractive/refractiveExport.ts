import type { GlassmorphismPaint, LiquidChromePaint } from './types.ts'
import { glassmorphismFragmentShader, glassmorphismUniforms } from './glassmorphismFragment.ts'
import { liquidChromeFragmentShader, liquidChromeUniforms } from './liquidChromeFragment.ts'

export function exportGlassmorphismReact(paint: GlassmorphismPaint): string {
  const uniforms = glassmorphismUniforms(paint)
  const escapedGlsl = JSON.stringify(glassmorphismFragmentShader)

  return `// Generated by Paper (https://paper.design)
// Real-Time Physically-Modeled Glassmorphism Shader Material
import React from 'react'
import { ShaderMount } from '@paper-design/shaders-react'

export interface GlassmorphismMaterialProps {
  className?: string
  style?: React.CSSProperties
  speed?: number
  frame?: number
}

const FRAGMENT_SHADER = ${escapedGlsl}
const UNIFORMS = ${JSON.stringify(uniforms, null, 2)}

export default function GlassmorphismMaterial({
  className,
  style,
  speed = ${paint.speed},
  frame = ${paint.frame},
}: GlassmorphismMaterialProps) {
  return (
    <div
      className={className}
      style={{
        width: '100%',
        height: '100%',
        position: 'relative',
        overflow: 'hidden',
        mixBlendMode: ${JSON.stringify(paint.composite?.blendMode ?? 'normal')},
        opacity: ${paint.composite?.opacity ?? 1},
        ...style,
      }}
    >
      <ShaderMount
        fragmentShader={FRAGMENT_SHADER}
        uniforms={UNIFORMS}
        speed={speed}
        frame={frame}
        style={{ position: 'absolute', inset: 0, width: '100%', height: '100%' }}
      />
    </div>
  )
}
`
}

