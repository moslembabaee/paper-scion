import type { ShaderPaint } from '../types.ts'
import { multiPassFragmentShader, multiPassUniforms, pipelineModulationUniforms } from './multiPassFragment.ts'
import { SILENT_AUDIO, audioSignals } from '../audio/types.ts'

export function exportPipelineReact(paint: Extract<ShaderPaint, { kind: 'multi-pass' }>): string {
  const style = {
    width: '100%',
    height: '100%',
    opacity: paint.composite?.opacity ?? 1,
    mixBlendMode: paint.composite?.blendMode ?? 'normal',
  }
  const uniforms = multiPassUniforms(paint)
  const audioMods = paint.pipeline?.modulators.filter(mod => mod.enabled && mod.source && mod.source !== 'lfo') ?? []
  const hasAudio = audioMods.length > 0
  const baseUniforms = multiPassUniforms({ ...paint, pipeline: paint.pipeline ? { ...paint.pipeline, modulators: paint.pipeline.modulators.filter(mod => !audioMods.includes(mod)) } : undefined })
  const bindings = audioMods.flatMap(mod => {
    const pass = paint.pipeline?.passes.find(pass => pass.id === mod.targetPassId)
    const binding = pass && pipelineModulationUniforms[pass.type]?.[mod.targetParam]
    return binding ? [{ uniform: binding[0], base: baseUniforms[binding[0]], min: binding[1], max: binding[2], source: mod.source, depth: mod.amplitude * paint.params.modulatorDepth }] : []
  })
  const audioImports = hasAudio ? `import type { PaperShaderElement } from '@paper-design/shaders-react';
import { useEffect, useRef } from 'react';
` : ''
  const audioSetup = hasAudio ? `
type AudioFrame = { ${audioSignals.map(signal => `${signal}: number`).join('; ')} };
const silentAudio: AudioFrame = ${JSON.stringify(SILENT_AUDIO)};
const readSilence = () => silentAudio;
const audioBindings = ${JSON.stringify(bindings, null, 2)} as const;
` : ''
  const audioEffect = hasAudio ? `
  const ref = useRef<PaperShaderElement>(null);
  useEffect(() => {
    if (!${paint.animated}) return; // Static mode preserves the saved frame.
    let request = 0;
    const tick = () => {
      const audio = getAudioFrame();
      const next: Record<string, number> = {};
      for (const [key, value] of Object.entries(audio)) next['u_audio_' + key] = value;
      for (const binding of audioBindings) {
        next[binding.uniform] = (next[binding.uniform] ?? binding.base) + audio[binding.source] * binding.depth;
      }
      for (const binding of audioBindings) next[binding.uniform] = Math.max(binding.min, Math.min(binding.max, next[binding.uniform]));
      ref.current?.paperShaderMount?.setUniforms(next);
      request = requestAnimationFrame(tick);
    };
    request = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(request);
  }, [getAudioFrame]);
` : ''

  return `import { ShaderMount } from '@paper-design/shaders-react';
${audioImports}

// Multi-Pass Shader Pipeline (${paint.pipeline?.name ?? 'Custom Material'})
// Generated by Paper (https://github.com/moslembabaee/paper)
const fragmentShader = \`${multiPassFragmentShader}\`;

const uniforms = ${JSON.stringify(uniforms, null, 2)};
${audioSetup}

// For live audio, pass a stable getAudioFrame callback backed by your Web Audio analyser.
export default function MaterialComposer(${hasAudio ? '{ getAudioFrame = readSilence }: { getAudioFrame?: () => Readonly<AudioFrame> }' : ''}) {
${audioEffect}
  return (
    <ShaderMount
      ${hasAudio ? 'ref={ref}' : ''}
      fragmentShader={fragmentShader}
      uniforms={uniforms}
      speed={${paint.animated ? paint.speed : 0}}
      frame={${paint.frame}}
      minPixelRatio={1}
      maxPixelCount={1500000}
      style={${JSON.stringify(style, null, 2)}}
    />
  );
}
`
}

export function exportPipelineGLSL(): string {
  return multiPassFragmentShader
}

export function exportPipelineUniforms(paint: Extract<ShaderPaint, { kind: 'multi-pass' }>): string {
  return JSON.stringify(multiPassUniforms(paint), null, 2)
}
