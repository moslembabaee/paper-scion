export const MATERIAL_PRESETS_MAP = new Map<MaterialPresetId, MaterialPresetDefinition>(
  MATERIAL_PRESETS.map(preset => [preset.id, preset])
)

export function getMaterialPreset(id: MaterialPresetId | string): MaterialPresetDefinition {
  return MATERIAL_PRESETS_MAP.get(id as MaterialPresetId) ?? MATERIAL_PRESETS[0]
}

export function createDefaultMaterialParams(presetId: MaterialPresetId = 'iridescent-film'): MaterialPresetParams {
  const preset = getMaterialPreset(presetId)
  return { ...preset.params, colors: [...preset.params.colors] }
}
