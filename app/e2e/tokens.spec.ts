import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { waitForCanvasReady } from './helpers'

// Each test has a fresh browser context. Keep its storage intact across reloads.
test.beforeEach(async ({ page }) => { await waitForCanvasReady(page, false) })

async function addToken(page: Page, type: string, name: string, value: string) {
  await page.getByRole('tab', { name: 'Theme / Tokens' }).click()
  await page.getByRole('button', { name: 'Add token', exact: true }).click()
  await page.getByLabel('Token type', { exact: true }).selectOption(type)
  await page.getByLabel('Token name', { exact: true }).fill(name)
  await page.getByLabel('Token value', { exact: true }).fill(value)
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

test('color tokens update bound canvas nodes, detach without changing appearance, and persist', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.getByTestId('tool-rectangle').click()
  const id = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  const rect = page.locator(`[data-element-id="${id}"] rect`)
  await addToken(page, 'color', 'brand-blue', '#81adec')
  await page.getByLabel('Fill token', { exact: true }).selectOption({ label: 'brand-blue · #81adec' })
  await page.getByTestId('theme-panel').getByRole('button', { name: /brand-blue/ }).click()
  await page.getByLabel('Token value', { exact: true }).fill('#222222')
  await page.getByLabel('Token name', { exact: true }).click() // value autosaves on blur
  await expect(rect).toHaveAttribute('fill', '#222222')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByTestId('dev-mode-toggle').click()
  await expect(page.getByTestId('dev-mode-panel')).toContainText('var(--color-brand-blue)')
  await page.getByTestId('dev-mode-panel').getByRole('button', { name: 'Code', exact: true }).click()
  await expect(page.getByTestId('dev-mode-panel')).toContainText('bg-brand-blue')
  await expect(page.getByTestId('dev-mode-panel')).toContainText('@theme static')
  await page.getByRole('button', { name: 'Exit dev mode' }).click()
  await page.getByRole('button', { name: 'Detach fill token' }).click()
  await expect(rect).toHaveAttribute('fill', '#222222')
  await page.getByTestId('theme-panel').getByRole('button', { name: /brand-blue/ }).click()
  await page.getByLabel('Token value', { exact: true }).fill('#edebe1')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(rect).toHaveAttribute('fill', '#222222')
  // Allow the project's normal autosave debounce to finish before reload.
  await expect(page.locator('.local-status')).toContainText('Saved', { timeout: 10000 })
  await page.reload()
  await page.getByRole('tab', { name: 'Theme / Tokens' }).click()
  await expect(page.getByTestId('theme-panel')).toContainText('brand-blue')
  await expect(page.getByTestId('theme-panel')).toContainText('#edebe1')
  await expect(rect).toHaveAttribute('fill', '#222222')
  expect(errors).toEqual([])
})

test('radius and typography selectors resolve tokens and Backspace detaches', async ({ page }) => {
  await addToken(page, 'radius', 'card', '16')
  await page.getByTestId('tool-rectangle').click()
  const rect = page.locator('.scene-node.is-selected rect')
  await page.getByLabel('Radius token', { exact: true }).selectOption({ label: 'card · 16px' })
  await expect(rect).toHaveAttribute('rx', '16')
  await page.getByLabel('Radius token', { exact: true }).press('Backspace')
  await expect(page.getByLabel('Radius token', { exact: true })).toHaveValue('')
  await expect(rect).toHaveAttribute('rx', '16')
  await addToken(page, 'fontSize', 'heading', '48')
  await addToken(page, 'fontFamily', 'editorial', 'Georgia, serif')
  await page.getByTestId('tool-text').click()
  await page.getByLabel('Font size token', { exact: true }).selectOption({ label: 'heading · 48px' })
  await page.getByLabel('Font family token', { exact: true }).selectOption({ label: 'editorial · Georgia, serif' })
  await expect(page.locator('.scene-node.is-selected .scene-text')).toHaveCSS('font-size', '48px')
  await expect(page.locator('.scene-node.is-selected .scene-text')).toHaveCSS('font-family', 'Georgia, serif')
  await page.getByLabel('Font family', { exact: true }).focus()
  await page.getByLabel('Font size', { exact: true }).focus()
  await expect(page.getByLabel('Font family token', { exact: true })).not.toHaveValue('')
})

test('context duplicate, CSS paste, multi-select deletion and undo keep tokens consistent', async ({ page }) => {
  await addToken(page, 'color', 'ink', '#080808')
  const panel = page.getByTestId('theme-panel')
  await panel.getByRole('button', { name: /ink/ }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Duplicate', exact: true }).click()
  await page.getByLabel('Token value', { exact: true }).fill('#222222')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(panel).toContainText('ink-copy')
  await page.evaluate(() => {
    const data = new DataTransfer()
    data.setData('text/plain', ':root {\n  --radius-soft: 8px;\n  --text-body: 16px;\n}')
    document.querySelector('[data-testid="theme-panel"]')!.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, clipboardData: data }))
  })
  await expect(panel).toContainText('soft')
  await expect(panel).toContainText('body')
  await panel.focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Delete')
  await expect(panel).toContainText('0 tokens')
  await page.getByTestId('history-undo').click()
  await expect(panel).toContainText('4 tokens')
})

test('clicking away saves new tokens and invalid edits can be canceled', async ({ page }) => {
  await page.getByRole('tab', { name: 'Theme / Tokens' }).click()
  await page.getByRole('button', { name: 'Add token', exact: true }).click()
  await page.getByLabel('Token name', { exact: true }).fill('accent')
  await page.getByLabel('Token value', { exact: true }).fill('#81adec')
  await page.mouse.click(10, 10)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const panel = page.getByTestId('theme-panel')
  await panel.getByRole('button', { name: /accent/ }).click()
  await page.getByLabel('Token value', { exact: true }).fill('invalid-color')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('valid CSS color')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(panel).toContainText('#81adec')
})
