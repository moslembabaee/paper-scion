import { test, expect } from '@playwright/test'
import { waitForCanvasReady } from './helpers'

test.beforeEach(async ({ page }) => { await waitForCanvasReady(page) })

test('mask toolbar preserves source layers and supports hierarchy toggles, editing, release and undo', async ({ page }) => {
  const inspector = page.getByTestId('inspector-panel')
  const set = async (label: string, value: string) => { const input = inspector.getByLabel(label, { exact: true }); await input.fill(value); await input.press('Enter') }
  await page.getByTestId('tool-rectangle').click()
  await set('Layer name', 'Mask content'); await set('Width', '180'); await set('Height', '180')
  const x = Number(await inspector.getByLabel('X', { exact: true }).inputValue()), y = Number(await inspector.getByLabel('Y', { exact: true }).inputValue())
  await page.getByTestId('tool-rectangle').click()
  await set('Layer name', 'Clip source'); await set('Width', '100'); await set('Height', '100')
  await set('X', String(x + 40)); await set('Y', String(y + 40)); await set('Radius', '20')
  await page.getByTestId('layer-tree').getByTitle('Mask content', { exact: true }).click({ modifiers: ['Shift'] })
  await page.getByRole('button', { name: 'Use top layer as mask', exact: true }).click()
  const group = page.locator('.scene-node[aria-label="Mask group"]')
  await expect(group).toHaveCount(1)
  await expect(group.locator('.scene-children').first()).toHaveAttribute('data-mask-source', /.+/)
  await expect(group.locator('clipPath path')).toHaveAttribute('d', /C/)
  await expect(page.locator('.scene-node[aria-label="Mask content"]')).toHaveCount(1)
  await expect(page.locator('.scene-node[aria-label="Clip source"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Deselect elements', exact: true }).click()
  const bounds = (await group.boundingBox())!
  await page.mouse.click(bounds.x + bounds.width * 70 / 180, bounds.y + bounds.height * 70 / 180)
  await expect(page.locator('.scene-node[aria-label="Mask content"]')).toHaveClass(/is-selected/)
  await page.getByRole('button', { name: 'Deselect elements', exact: true }).click()
  await page.mouse.click(bounds.x + bounds.width * 10 / 180, bounds.y + bounds.height * 10 / 180)
  await expect(page.locator('.scene-node[aria-label="Mask content"]')).not.toHaveClass(/is-selected/)
  await page.getByTestId('layer-tree').getByTitle('Mask group', { exact: true }).click()
  await page.getByRole('switch', { name: 'Show mask outline', exact: true }).click()
  await expect(group.locator('.scene-mask-outline')).toHaveCount(1)
  await page.getByRole('button', { name: 'Expand Mask group', exact: true }).click()
  const sourceLayer = page.getByTestId('layer-tree').locator('.scene-layer-row.is-mask')
  await expect(sourceLayer).toContainText('MASK')
  await sourceLayer.getByRole('button', { name: 'Disable Clip source mask', exact: true }).click()
  await expect(group.locator('.scene-children').first()).not.toHaveAttribute('data-mask-source')
  await expect(page.locator('.scene-node[aria-label="Clip source"]')).toHaveCount(1)
  await sourceLayer.getByRole('button', { name: 'Enable Clip source mask', exact: true }).click()
  await sourceLayer.getByTitle('Clip source', { exact: true }).click()
  const before = await group.locator('clipPath path').getAttribute('d')
  await set('Width', '120')
  await expect(group.locator('clipPath path')).not.toHaveAttribute('d', before!)
  await page.getByTestId('history-undo').click()
  await expect(group.locator('clipPath path')).toHaveAttribute('d', before!)
  await page.getByRole('button', { name: 'Release mask', exact: true }).click()
  await expect(group.locator('clipPath')).toHaveCount(0)
  await expect(page.locator('.scene-node[aria-label="Clip source"]')).toHaveCount(1)
  await page.getByTestId('history-undo').click()
  await expect(group.locator('clipPath')).toHaveCount(1)
})
