import { test, expect } from '@playwright/test'
import { waitForCanvasReady, waitForViewportSettled } from './helpers'

test('component library, property overrides, master propagation, reset and detach survive reload', async ({ page }) => {
  await waitForCanvasReady(page)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const inspector = page.getByTestId('inspector-panel')
  const edit = async (name: string, value: string) => {
    const field = inspector.getByRole('textbox', { name, exact: true })
    await field.fill(value)
    await field.press('Enter')
  }
  await page.getByTestId('tool-rectangle').click()
  const masterId = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  await edit('Layer name', 'Surface')
  await inspector.getByRole('button', { name: 'Create component', exact: true }).click()
  await expect(page.locator(`[data-element-id="${masterId}"]`)).toHaveAttribute('data-component-kind', 'master')
  await page.getByRole('tab', { name: 'Components', exact: true }).click()
  await expect(page.getByTestId('component-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Insert Surface instance', exact: true }).click()
  const instance = page.locator(`[data-component-master="${masterId}"]`)
  const instanceId = await instance.getAttribute('data-element-id')
  await waitForViewportSettled(page)
  await edit('Fill color', '#edebe1')
  await expect(inspector.getByTestId('component-inspector')).toHaveCount(1)
  await expect(inspector.getByRole('combobox', { name: 'Width sizing', exact: true })).toHaveCount(1)
  await expect(inspector.getByTestId('component-inspector')).toContainText('1 local override')
  await inspector.getByRole('button', { name: 'Go to master', exact: true }).click()
  await edit('Fill color', '#222222')
  const radius = inspector.getByRole('spinbutton', { name: 'Radius', exact: true })
  await radius.fill('16')
  await radius.press('Enter')
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#edebe1')
  await expect(instance.locator('rect')).toHaveAttribute('rx', '16')
  await page.getByRole('tab', { name: 'Layers', exact: true }).click()
  await page.locator(`[data-layer-id="${instanceId}"] .layer-select`).click()
  await inspector.getByRole('button', { name: 'Reset overrides', exact: true }).click()
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#222222')
  await expect(inspector.getByTestId('component-inspector')).toContainText('Synced with master')
  await page.getByTestId('history-undo').click()
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#edebe1')
  await expect(page.locator('.local-status')).toHaveText('Saved locally')
  await page.reload()
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#edebe1')
  await page.locator(`[data-layer-id="${instanceId}"] .layer-select`).click()
  await inspector.getByRole('button', { name: 'Detach instance', exact: true }).click()
  await expect(instance).toHaveCount(0)
  const detached = page.locator(`[data-element-id="${instanceId}"]`)
  await expect(detached.locator('rect')).toHaveAttribute('fill', '#edebe1')
  await expect(detached).not.toHaveAttribute('data-component-kind')
  await expect(inspector.getByRole('button', { name: 'Create component', exact: true })).toBeEnabled()
  await page.getByTestId('history-undo').click()
  await expect(instance).toHaveCount(1)
  await expect(errors).toEqual([])
  await page.getByRole('tab', { name: 'Components', exact: true }).click()
  await page.screenshot({ path: '/tmp/paper-components-library.png' })
})

test('frame instances synchronize text while retaining local copy and expose child reset', async ({ page }) => {
  await waitForCanvasReady(page)
  const inspector = page.getByTestId('inspector-panel')
  await page.getByTestId('tool-frame').click()
  const masterId = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  const name = inspector.getByRole('textbox', { name: 'Layer name', exact: true })
  await name.fill('Card')
  await name.press('Enter')
  await page.getByTestId('tool-text').click()
  const textId = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  await page.locator(`[data-layer-id="${masterId}"] .layer-select`).click()
  await inspector.getByRole('button', { name: 'Create component', exact: true }).click()
  await inspector.getByRole('button', { name: 'Insert instance', exact: true }).click()
  const instance = page.locator(`[data-component-master="${masterId}"][data-element-type="frame"]`)
  const instanceId = await instance.getAttribute('data-element-id')
  await page.locator(`[data-layer-id="${instanceId}"]`).getByRole('button', { name: 'Expand Card', exact: true }).click()
  const child = instance.locator('[data-element-type="text"]')
  const childId = await child.getAttribute('data-element-id')
  await page.locator(`[data-layer-id="${childId}"] .layer-select`).click()
  const copy = inspector.getByRole('textbox', { name: 'Text content', exact: true })
  await copy.fill('Made for this instance.')
  await copy.blur()
  await expect(child).toContainText('Made for this instance.')
  await expect(inspector.getByRole('button', { name: 'Delete selected element', exact: true })).toBeDisabled()
  await inspector.getByRole('button', { name: 'Go to master', exact: true }).click()
  await page.locator(`[data-layer-id="${masterId}"]`).getByRole('button', { name: 'Expand Card', exact: true }).click()
  await page.locator(`[data-layer-id="${textId}"] .layer-select`).click()
  await copy.fill('Updated master copy.')
  await copy.blur()
  await expect(child).toContainText('Made for this instance.')
  await page.locator(`[data-layer-id="${childId}"] .layer-select`).click()
  await inspector.getByRole('button', { name: 'Reset overrides', exact: true }).click()
  await expect(child).toContainText('Updated master copy.')
  await expect(inspector.getByTestId('component-inspector')).toContainText('Synced with master')
})

test('named variants capture master appearance and instance switches persist with elevation tokens', async ({ page }) => {
  await waitForCanvasReady(page)
  const inspector = page.getByTestId('inspector-panel')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.getByTestId('tool-rectangle').click()
  const masterId = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  await inspector.getByRole('button', { name: 'Create component', exact: true }).click()
  await inspector.getByRole('button', { name: 'Add component property', exact: true }).click()
  await inspector.getByRole('textbox', { name: 'Property name', exact: true }).fill('Tone')
  await inspector.getByRole('button', { name: 'Add property', exact: true }).click()
  await inspector.getByRole('button', { name: 'Capture Tone Default', exact: true }).click()
  const fill = inspector.getByRole('textbox', { name: 'Fill color', exact: true })
  await fill.fill('#222222')
  await fill.press('Enter')
  await inspector.getByRole('button', { name: 'Capture Tone Accent', exact: true }).click()
  await inspector.getByRole('button', { name: 'Insert instance', exact: true }).click()
  const instance = page.locator(`[data-component-master="${masterId}"]`)
  const instanceId = await instance.getAttribute('data-element-id')
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#81adec')
  await inspector.getByRole('combobox', { name: 'Tone', exact: true }).selectOption('Accent')
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#222222')
  await page.getByRole('tab', { name: 'Theme / Tokens', exact: true }).click()
  await page.getByRole('button', { name: 'Add foundation tokens', exact: true }).click()
  await inspector.getByRole('combobox', { name: 'Elevation token', exact: true }).selectOption({ label: 'raised · 4px' })
  await expect(inspector.getByRole('spinbutton', { name: 'Shadow Y', exact: true })).toHaveValue('4')
  await expect(page.locator('.local-status')).toHaveText('Saved locally')
  await page.reload()
  await page.getByRole('tab', { name: 'Layers', exact: true }).click()
  await page.locator(`[data-layer-id="${instanceId}"] .layer-select`).click()
  await expect(inspector.getByRole('combobox', { name: 'Tone', exact: true })).toHaveValue('Accent')
  await expect(instance.locator('rect')).toHaveAttribute('fill', '#222222')
  await expect(inspector.getByRole('combobox', { name: 'Elevation token', exact: true })).toContainText('raised')
  await expect(errors).toEqual([])
  await page.screenshot({ path: '/tmp/paper-component-properties.png' })
})
