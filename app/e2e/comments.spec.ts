import { mockStudioSession } from './studio-session'
import { expect, test } from '@playwright/test'
import { waitForCanvasReady, waitForViewportSettled } from './helpers'
import type { Page } from '@playwright/test'

async function placeComment(page: Page, body: string, point?: { x: number; y: number }) {
  if (!await page.getByTestId('comments-sidebar').isVisible()) await page.getByTestId('tool-comments').click()
  await page.getByRole('button', { name: 'Place a comment', exact: true }).click()
  const viewport = await page.getByTestId('canvas-viewport').boundingBox()
  await page.mouse.click(point?.x ?? viewport!.x + 110, point?.y ?? viewport!.y + 170)
  await page.getByRole('textbox', { name: 'Write a comment' }).fill(body)
  await page.getByRole('button', { name: 'Post comment', exact: true }).click()
  await expect(page.getByTestId('comment-thread')).toContainText(body)
}

test('canvas pins follow layers, threads support mentions and statuses, and persist on reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await waitForCanvasReady(page)
  await page.getByTestId('tool-rectangle').click()
  const node = page.locator('.scene-node.is-selected'), id = await node.getAttribute('data-element-id')
  const box = await node.boundingBox()
  await placeComment(page, 'Check this spacing, @paperdesigner', { x: box!.x + box!.width / 2, y: box!.y + box!.height / 2 })
  await expect(page.locator('.comment-location')).toContainText('Rectangle')
  const pin = page.getByTestId('comment-pin').first(), pinBefore = await pin.boundingBox()
  const position = page.getByRole('spinbutton', { name: 'X', exact: true })
  const x = Number(await position.inputValue())
  await position.fill(String(x + 120)); await position.press('Enter')
  const zoom = await page.getByTestId('viewport-world').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m11)
  await expect.poll(async () => (await pin.boundingBox())!.x - pinBefore!.x).toBeCloseTo(120 * zoom, 1)
  await page.getByRole('textbox', { name: 'Write a reply' }).fill('Hello @pap')
  await page.getByRole('button', { name: /Paper Designer.*@paperdesigner/ }).click()
  await expect(page.getByRole('textbox', { name: 'Write a reply' })).toHaveValue('Hello @paperdesigner ')
  await page.getByRole('textbox', { name: 'Write a reply' }).press('Control+Enter')
  await expect(page.locator('.comment-message')).toHaveCount(2)
  await page.getByRole('button', { name: 'Resolve thread', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Write a reply' })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Filter comments' }).selectOption('resolved')
  await expect(page.getByTestId('comment-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Reopen thread', exact: true }).click()
  await page.getByRole('combobox', { name: 'Filter comments' }).selectOption('mentions')
  await expect(page.getByTestId('comment-row')).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Search comments' }).fill('no matching text')
  await expect(page.getByTestId('comment-row')).toHaveCount(0)
  await page.getByRole('button', { name: 'Clear comment search' }).click()
  await page.getByRole('button', { name: 'Back to comment list' }).click()
  await page.getByRole('button', { name: 'Next comment' }).click()
  await expect(page.getByTestId('comment-thread')).toBeVisible()
  await waitForViewportSettled(page)
  await expect(page.locator('.local-status')).toHaveText('Saved locally')
  await page.screenshot({ path: '/tmp/paper-comments.png' })
  await page.reload()
  await expect(page.locator(`[data-element-id="${id}"]`)).toBeAttached()
  await page.getByTestId('tool-comments').click()
  await expect(page.getByTestId('comment-row')).toHaveCount(1)
  await page.getByTestId('comment-row').click()
  await expect(page.locator('.comment-message')).toHaveCount(2)
  expect(errors).toEqual([])
})

test('invited browsers share threads and replies with private unread state and offline recovery', async ({ page, browser }) => {
  test.setTimeout(60000)
  await waitForCanvasReady(page)
  await page.getByRole('button', { name: 'Canvas collaborators', exact: true }).click()
  await page.getByRole('button', { name: 'Copy invite link', exact: true }).click()
  await expect(page.locator('.presence-connection')).toHaveText('Live')
  const invite = await page.getByRole('textbox', { name: 'Canvas invite link' }).inputValue()
  await page.getByRole('button', { name: 'Canvas collaborators', exact: true }).click()
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  try {
    await context.addInitScript(() => localStorage.setItem('paper.profile.v1', JSON.stringify({ version: 1, name: 'Mira Chen' })))
    const peer = await context.newPage()
    await mockStudioSession(peer)
    await peer.goto(invite)
    await expect(peer.getByTestId('canvas-viewport')).toBeVisible()
    await expect(page.locator('.presence-avatar[title^="Mira Chen"]')).toBeVisible()
    await placeComment(page, 'Review the rhythm, @mirachen')
    await expect(peer.locator('.comment-tool-unread')).toHaveText('1')
    await peer.getByTestId('tool-comments').click()
    await peer.getByRole('combobox', { name: 'Filter comments' }).selectOption('mentions')
    await expect(peer.getByTestId('comment-row')).toHaveCount(1)
    await peer.getByTestId('comment-row').click()
    await expect(peer.locator('.comment-tool-unread')).toHaveCount(0)
    await page.getByRole('button', { name: 'Close comments' }).click()
    await peer.getByRole('textbox', { name: 'Write a reply' }).fill('A little more room here.')
    await peer.getByRole('button', { name: 'Post reply', exact: true }).click()
    await expect(page.locator('.comment-tool-unread')).toHaveText('1')
    await page.getByTestId('tool-comments').click()
    await expect(page.locator('.comment-message')).toHaveCount(2)
    await expect(page.locator('.comment-tool-unread')).toHaveCount(0)
    await peer.getByRole('button', { name: 'Resolve thread' }).click()
    await expect(page.getByRole('button', { name: 'Reopen thread' })).toBeVisible()
    await page.getByRole('button', { name: 'Reopen thread' }).click()
    await expect(peer.getByRole('textbox', { name: 'Write a reply' })).toBeVisible()
    await context.setOffline(true)
    await peer.getByRole('textbox', { name: 'Write a reply' }).fill('Saved while offline')
    await peer.getByRole('button', { name: 'Post reply' }).click()
    await context.setOffline(false)
    await expect(page.getByTestId('comment-thread')).toContainText('Saved while offline', { timeout: 15000 })
  } finally { await context.close() }
})
