import { test, expect, type Page } from '@playwright/test'
import { drag, drawVectorPath, expectZoom, waitForCanvasReady } from './helpers'

const anchor = (page: Page, contour: number, index: number) => page.locator(`.pen-anchor[data-contour="${contour}"][data-anchor="${index}"]`)
const center = async (locator: ReturnType<typeof anchor>) => { const b = (await locator.boundingBox())!; return { x: b.x + b.width / 2, y: b.y + b.height / 2 } }

async function editPath(page: Page, d?: string) {
  await waitForCanvasReady(page)
  await drawVectorPath(page)
  if (d) { await page.getByLabel('SVG path data', { exact: true }).fill(d); await page.getByLabel('SVG path data', { exact: true }).press('Tab') }
  await page.getByTestId('zoom-value').click()
  await page.getByTestId('zoom-menu').getByRole('button', { name: '100%', exact: true }).click()
  await expectZoom(page, 1)
  const path = page.locator('.scene-node[data-element-type="path"].is-selected')
  if (d) await page.getByTestId('canvas-viewport').press('Enter')
  else await path.dblclick({ position: { x: 60, y: 80 }, force: true })
  await expect(page.getByTestId('node-inspector')).toBeVisible()
  return path
}

test('double-click editing offers constrained handles, corner radius, and persistent undo', async ({ page }) => {
  const path = await editPath(page)
  await expect(page.locator('.pen-anchor')).toHaveCount(3)
  const outline = path.locator('path'), before = await outline.getAttribute('d')
  await anchor(page, 0, 1).click()
  await expect(outline).toHaveAttribute('d', before!)
  const panel = page.getByTestId('node-inspector')
  await panel.getByRole('button', { name: 'Mirrored', exact: true }).click()
  const incoming = page.locator('.pen-control[data-control="in"]'), outgoing = page.locator('.pen-control[data-control="out"]')
  await expect(incoming).toHaveCount(1)
  const origin = await center(anchor(page, 0, 1)), from = await center(outgoing)
  await drag(page, from, { x: origin.x + 30, y: origin.y + 20 })
  const i = await center(incoming), o = await center(outgoing)
  expect(i.x + o.x).toBeCloseTo(origin.x * 2, 1)
  expect(i.y + o.y).toBeCloseTo(origin.y * 2, 1)
  await panel.getByRole('button', { name: 'Disconnected', exact: true }).click()
  const independent = await center(incoming)
  await drag(page, await center(outgoing), { x: origin.x + 40, y: origin.y + 10 })
  expect(await center(incoming)).toEqual(independent)
  await panel.getByRole('button', { name: 'Corner', exact: true }).click()
  await panel.getByLabel('Node Corner radius').fill('8')
  await panel.getByLabel('Node Corner radius').press('Enter')
  await expect(outline).toHaveAttribute('d', / C /)
  await page.getByTestId('history-undo').click()
  await expect(panel.getByLabel('Node Corner radius')).toHaveValue('0')
  await page.getByTestId('history-redo').click()
  await expect(panel.getByLabel('Node Corner radius')).toHaveValue('8')
  await page.getByRole('button', { name: 'Done' }).click()
  await expect(page.getByTestId('pen-overlay')).toHaveCount(0)
  await page.getByTestId('canvas-viewport').press('Enter')
  await anchor(page, 0, 1).click()
  await expect(panel.getByLabel('Node Corner radius')).toHaveValue('8')
})

test('selects and edits independent subpaths, inserts on an edge, and reverses deletion', async ({ page }) => {
  await editPath(page, 'M0 0H48V48H0Z M72 72H120V120H72Z')
  await expect(page.locator('.pen-anchor')).toHaveCount(8)
  const a = await center(anchor(page, 0, 0)), b = await center(anchor(page, 1, 0))
  await anchor(page, 0, 0).click()
  await anchor(page, 1, 0).click({ modifiers: ['Shift'] })
  await expect(page.locator('.pen-anchor.is-active')).toHaveCount(2)
  await page.keyboard.press('ArrowRight')
  expect((await center(anchor(page, 0, 0))).x).toBeCloseTo(a.x + 1, 1)
  expect((await center(anchor(page, 1, 0))).x).toBeCloseTo(b.x + 1, 1)
  await page.keyboard.press('Backspace')
  await expect(page.locator('.pen-anchor')).toHaveCount(6)
  await page.getByTestId('history-undo').click()
  await expect(page.locator('.pen-anchor')).toHaveCount(8)
  const from = await center(anchor(page, 0, 1)), to = await center(anchor(page, 0, 2))
  await page.mouse.dblclick((from.x + to.x) / 2, (from.y + to.y) / 2)
  await expect(page.locator('.pen-anchor')).toHaveCount(9)
  await expect(page.locator('.pen-anchor.is-active')).toHaveCount(1)
  await page.getByTestId('history-undo').click()
  await expect(page.locator('.pen-anchor')).toHaveCount(8)
})

test('Escape cancels a live node drag without losing the edit session', async ({ page }) => {
  const path = await editPath(page)
  const before = await path.locator('path').getAttribute('d'), from = await center(anchor(page, 0, 1))
  await page.mouse.move(from.x, from.y); await page.mouse.down()
  await page.mouse.move(from.x + 35, from.y + 20, { steps: 5 })
  await expect(path.locator('path')).not.toHaveAttribute('d', before!)
  await page.keyboard.press('Escape'); await page.mouse.up()
  await expect(path.locator('path')).toHaveAttribute('d', before!)
  await expect(page.getByTestId('node-inspector')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('pen-overlay')).toHaveCount(0)
})
