import { test, expect } from '@playwright/test'
import { waitForCanvasReady, expectZoom } from './helpers'

test.beforeEach(async ({ page }) => { await waitForCanvasReady(page) })

test('dragging simulates motion, pause freezes it, and exit restores document geometry', async ({ page }) => {
  await page.getByTestId('zoom-value').click()
  await page.getByTestId('zoom-menu').getByRole('button', { name: '100%', exact: true }).click()
  await expectZoom(page, 1)
  await page.getByTestId('tool-rectangle').click()
  const node = page.locator('.scene-node.is-selected')
  const original = await node.getAttribute('style')
  const bounds = (await node.boundingBox())!
  await page.getByTestId('tool-physics').click()
  await expect(page.getByTestId('physics-panel')).toContainText('1 body')
  await page.getByRole('button', { name: 'Elastic', exact: true }).click()
  await expect(page.getByRole('slider', { name: 'Damping', exact: true })).toHaveValue('7')
  await page.mouse.move(bounds.x + 60, bounds.y + 60)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 150, bounds.y + 100, { steps: 8 })
  await expect.poll(() => node.evaluate(el => el.style.translate)).not.toMatch(/^(0px( 0px)?|)$/)
  await page.mouse.up()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const frozen = await node.evaluate(el => el.style.translate)
  await page.waitForTimeout(150)
  expect(await node.evaluate(el => el.style.translate)).toBe(frozen)
  await page.getByRole('checkbox', { name: 'Spring to origin' }).uncheck()
  await expect(page.locator('[data-spring]').first()).toHaveCSS('visibility', 'hidden')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect.poll(() => node.evaluate(el => el.style.translate)).toMatch(/^(0px( 0px)?)$/)
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.waitForTimeout(150)
  expect(await node.evaluate(el => el.style.translate)).toMatch(/^(0px( 0px)?)$/)
  await page.getByRole('button', { name: 'Close physics simulation' }).click()
  await expect(page.getByTestId('physics-overlay')).toHaveCount(0)
  await expect(node).toHaveAttribute('style', original!)
})

test('physics controls support presets, magnets, pan, zoom and Escape', async ({ page }) => {
  await page.getByTestId('tool-physics').click()
  await page.getByRole('checkbox', { name: 'Spring to origin' }).uncheck()
  await expect(page.getByRole('checkbox', { name: 'Magnetic grid' })).toBeEnabled()
  await page.getByRole('checkbox', { name: 'Node collisions' }).uncheck()
  await page.getByRole('button', { name: 'Gentle', exact: true }).click()
  await expect(page.getByRole('slider', { name: 'Mass', exact: true })).toHaveValue('1.4')
  const world = page.getByTestId('viewport-world')
  const before = await world.getAttribute('style')
  const viewport = (await page.getByTestId('canvas-viewport').boundingBox())!
  await page.mouse.move(viewport.x + viewport.width * .7, viewport.y + 100)
  await page.keyboard.down('Space')
  await page.mouse.down()
  await page.mouse.move(viewport.x + viewport.width * .7 + 50, viewport.y + 130, { steps: 4 })
  await page.mouse.up()
  await page.keyboard.up('Space')
  expect(await world.getAttribute('style')).not.toBe(before)
  const afterPan = await world.getAttribute('style')
  await page.mouse.wheel(0, -120)
  await expect.poll(() => world.getAttribute('style')).not.toBe(afterPan)
  await page.getByRole('slider', { name: 'Mass', exact: true }).focus()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('physics-panel')).toHaveCount(0)
})
