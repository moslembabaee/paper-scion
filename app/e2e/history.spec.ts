test('a continuous shader slider drag is one styling checkpoint', async ({ page }) => {
  await page.getByTestId('tool-rectangle').click()
  await page.getByLabel('Paper shader effect').selectOption('mesh-gradient')
  const slider = page.getByLabel('Shader Scale slider', { exact: true })
  await slider.scrollIntoViewIfNeeded()
  const original = await slider.inputValue()
  const bounds = (await slider.boundingBox())!
  await drag(page, { x: bounds.x + bounds.width * .25, y: bounds.y + bounds.height / 2 }, { x: bounds.x + bounds.width * .75, y: bounds.y + bounds.height / 2 }, { steps: 20 })
  await expect(slider).not.toHaveValue(original)
  await page.getByTestId('history-undo').click()
  await expect(slider).toHaveValue(original)
  await page.getByTestId('history-undo').click()
  await expect(page.getByLabel('Paper shader effect')).toHaveValue('')
})
