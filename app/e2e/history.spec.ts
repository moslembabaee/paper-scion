import { test, expect } from '@playwright/test'
import { drag, waitForCanvasReady } from './helpers'

test.beforeEach(async ({ page }) => { await waitForCanvasReady(page) })

test('toolbar and Ctrl/Cmd shortcuts undo and redo creation with selection', async ({ page }) => {
  const undo = page.getByRole('button', { name: 'Undo', exact: true })
  const redo = page.getByRole('button', { name: 'Redo', exact: true })
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  await page.getByTestId('tool-rectangle').click()
  const id = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  const node = page.locator(`[data-element-id="${id}"]`)
  await expect(undo).toBeEnabled()
  await expect(undo).toHaveAttribute('title', /Add rectangle/)
  await undo.click()
  await expect(node).toHaveCount(0)
  await expect(undo).toBeDisabled()
  await expect(redo).toBeEnabled()
  await redo.click()
  await expect(node).toHaveClass(/is-selected/)
  await expect(page.getByTestId('selection-box')).toBeVisible()
  await page.getByTestId('canvas-viewport').focus()
  await page.keyboard.press('Control+z')
  await expect(node).toHaveCount(0)
  await page.keyboard.press('Control+Shift+z')
  await expect(node).toHaveClass(/is-selected/)
  await page.keyboard.press('Meta+z')
  await expect(node).toHaveCount(0)
  await page.keyboard.press('Meta+Shift+z')
  await expect(node).toHaveClass(/is-selected/)
})

test('a many-frame resize is one checkpoint', async ({ page }) => {
  await page.getByTestId('tool-rectangle').click()
  const id = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  const handle = (await page.locator('[data-handle="se"]').boundingBox())!
  await page.keyboard.down('Alt')
  await drag(page, { x: handle.x + handle.width / 2, y: handle.y + handle.height / 2 }, { x: handle.x + handle.width / 2 + 80, y: handle.y + handle.height / 2 + 60 }, { steps: 20 })
  await page.keyboard.up('Alt')
  const width = await page.getByLabel('Width', { exact: true }).inputValue()
  expect(Number(width)).toBeGreaterThan(120)
  await expect(page.getByTestId('history-undo')).toHaveAttribute('title', /Resize elements/)
  await page.keyboard.press('Control+z')
  await expect(page.getByLabel('Width', { exact: true })).toHaveValue('120')
  await page.keyboard.press('Control+Shift+z')
  await expect(page.getByLabel('Width', { exact: true })).toHaveValue(width)
  await page.keyboard.press('Control+z')
  await page.keyboard.press('Control+z')
  await expect(page.locator(`[data-element-id="${id}"]`)).toHaveCount(0)
})

test('Escape cancels a transform and preserves the redo branch', async ({ page }) => {
  await page.getByTestId('tool-rectangle').click()
  const x = page.getByLabel('X', { exact: true })
  const original = await x.inputValue()
  await x.fill(String(Number(original) + 120))
  await x.press('Enter')
  await page.getByTestId('history-undo').click()
  await expect(x).toHaveValue(original)
  await expect(page.getByTestId('history-redo')).toBeEnabled()
  const box = (await page.getByTestId('selection-box').boundingBox())!
  await page.keyboard.down('Alt')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 70, box.y + box.height / 2 + 50, { steps: 8 })
  await expect(x).not.toHaveValue(original)
  await expect(page.getByTestId('history-undo')).toBeDisabled()
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await page.keyboard.up('Alt')
  await expect(x).toHaveValue(original)
  await expect(page.getByTestId('history-redo')).toBeEnabled()
  await page.getByTestId('history-redo').click()
  await expect(x).toHaveValue(String(Number(original) + 120))
})

test('styling, ordering, and deletion restore the canvas and inspector', async ({ page }) => {
  await page.getByTestId('tool-rectangle').click()
  const id = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  const node = page.locator(`[data-element-id="${id}"]`)
  const fill = page.getByLabel('Fill color', { exact: true })
  await fill.fill('#222222')
  await fill.press('Enter')
  await expect(node.locator('rect')).toHaveAttribute('fill', '#222222')
  await page.getByTestId('history-undo').click()
  await expect(fill).toHaveValue('#81adec')
  await page.getByTestId('history-redo').click()
  await expect(node.locator('rect')).toHaveAttribute('fill', '#222222')
  const order = await node.evaluate(element => (element as HTMLElement).style.zIndex)
  await page.getByRole('button', { name: 'Send backward' }).click()
  await expect(node).toHaveCSS('z-index', String(Number(order) - 1))
  await page.getByTestId('history-undo').click()
  await expect(node).toHaveCSS('z-index', order)
  await page.getByRole('button', { name: 'Delete selected element' }).click()
  await expect(node).toHaveCount(0)
  await expect(page.getByTestId('history-redo')).toBeDisabled()
  await page.getByTestId('history-undo').click()
  await expect(node).toHaveClass(/is-selected/)
  await expect(fill).toHaveValue('#222222')
})

